#!/usr/bin/env node
// T9: check WCAG 2.1 contrast of the design tokens in both themes.
//
//   node scripts/check_contrast.mjs              # print a table; exit 1 if any pair fails
//   node scripts/check_contrast.mjs --markdown   # also write docs/ui/contrast.md
//
// Reads frontend/host/src/theme.css (the three apps' copies are identical; see
// check_theme_tokens.sh). Pairs and thresholds are from docs/design-t9-theming.md (T6).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(join(ROOT, 'frontend/host/src/theme.css'), 'utf8');

function parseBlock(selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`theme.css: no "${selector} {" block`);
  const body = css.slice(start, css.indexOf('}', start));
  const vars = {};
  for (const m of body.matchAll(/--([\w-]+):\s*(\d+)\s+(\d+)\s+(\d+)\s*;/g)) {
    vars[m[1]] = [Number(m[2]), Number(m[3]), Number(m[4])];
  }
  return vars;
}

const light = parseBlock(':root');
// The dark block only overrides; tokens it doesn't set (the option colors) inherit from light.
const themes = { light, dark: { ...light, ...parseBlock(':root.dark') } };

const channel = (c) => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const luminance = ([r, g, b]) => 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const blend = (top, alpha, under) => top.map((c, i) => c * alpha + under[i] * (1 - alpha));

// [foreground, background, threshold]. A background like 'danger/0.15' is that token
// alpha-blended over `surface` (the tinted status panels).
const pairs = [];
for (const fg of ['fg', 'fg-muted', 'fg-subtle']) {
  for (const bg of ['bg', 'surface', 'surface-raised']) pairs.push([fg, bg, 4.5]);
}
for (const bg of ['bg', 'surface', 'surface-raised']) pairs.push(['accent-fg', bg, 4.5]);
pairs.push(['on-accent', 'accent', 4.5], ['on-accent', 'accent-hover', 4.5]);
for (const fg of ['success-fg', 'danger-fg', 'warning-fg']) {
  for (const bg of ['bg', 'surface']) pairs.push([fg, bg, 4.5]);
}
pairs.push(['on-status', 'success', 4.5], ['on-status', 'danger', 4.5], ['on-warning', 'warning', 4.5]);
for (let n = 1; n <= 8; n++) pairs.push([`on-option-${n}`, `option-${n}`, 4.5]);
pairs.push(['danger-fg', 'danger/0.15', 4.5], ['success-fg', 'success/0.15', 4.5], ['warning-fg', 'warning/0.1', 4.5]);
pairs.push(['qr-fg', 'qr-bg', 4.5]);
for (const bg of ['bg', 'surface']) pairs.push(['focus', bg, 3], ['border-strong', bg, 3]);

function resolve(vars, name) {
  const [token, alpha] = name.split('/');
  const rgb = vars[token];
  if (!rgb) throw new Error(`theme.css: token --${token} is missing`);
  return alpha ? blend(rgb, Number(alpha), vars.surface) : rgb;
}

const rows = [];
let failures = 0;
for (const [fg, bg, min] of pairs) {
  const row = { fg, bg, min };
  for (const [theme, vars] of Object.entries(themes)) {
    const r = ratio(resolve(vars, fg), resolve(vars, bg));
    row[theme] = r;
    if (r < min) failures++;
  }
  rows.push(row);
}

const fmt = (r, min) => `${r.toFixed(2)}${r < min ? ' FAIL' : ''}`;
console.log(['foreground', 'background', 'min', 'light', 'dark'].map((h) => h.padEnd(16)).join(''));
for (const r of rows) {
  console.log([r.fg, r.bg, String(r.min), fmt(r.light, r.min), fmt(r.dark, r.min)].map((c) => c.padEnd(16)).join(''));
}
console.log(failures ? `\n${failures} pair(s) below their threshold.` : `\nAll ${rows.length} pairs pass in both themes.`);

if (process.argv.includes('--markdown')) {
  const out = join(ROOT, 'docs/ui/contrast.md');
  mkdirSync(dirname(out), { recursive: true });
  const md = [
    '# Theme contrast report',
    '',
    'Generated by `node scripts/check_contrast.mjs --markdown` from `frontend/*/src/theme.css`.',
    'Thresholds are WCAG 2.1: 4.5:1 for text (1.4.3), 3:1 for focus rings and input borders',
    '(1.4.11). A background like `danger/0.15` is that token at 15% over `surface`, the tinted',
    'status panels.',
    '',
    '| Foreground | Background | Minimum | Light | Dark |',
    '|---|---|---|---|---|',
    ...rows.map((r) => `| \`${r.fg}\` | \`${r.bg}\` | ${r.min} | ${fmt(r.light, r.min)} | ${fmt(r.dark, r.min)} |`),
    '',
    failures ? `**${failures} pair(s) fail.**` : `All ${rows.length} pairs pass in both themes.`,
    '',
  ].join('\n');
  writeFileSync(out, md);
  console.log(`Wrote ${out}`);
}

process.exit(failures ? 1 : 0);
